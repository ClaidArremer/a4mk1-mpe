#!/bin/sh
# Regenerate stub.s from mpe.c + hook.s (needs an m68k gcc; the build itself only
# assembles stub.s). Any m68k-elf gcc works: CC=m68k-elf-gcc ./gen.sh
set -e
cd "$(dirname "$0")"
CC=${CC:-m68k-elf-gcc}
$CC -mcpu=5475 -msoft-float -Os -ffreestanding -fno-builtin -fomit-frame-pointer \
    -fno-asynchronous-unwind-tables -fno-ident -Wall -Wextra -S mpe.c -o mpe.gen.s
{
  echo "| 0013-mpe - GENERATED by gen.sh from mpe.c and hook.s; edit those, not this."
  echo
  cat hook.s
  echo
  grep -v '^#NO_APP' mpe.gen.s
} > stub.s
rm -f mpe.gen.s
